namespace Termrig.Publisher
{
    using System;
    using System.Collections.Generic;
    using System.IO;
    using System.Linq;
    using System.Text;

    /// <summary>Writes the Inno Setup script for one Windows runtime identifier.</summary>
    public static class InnoScriptWriter
    {
        /// <summary>Returns the Windows AppId for a product identifier: a stable GUID wrapped in Inno's escaped braces.</summary>
        /// <param name="identifier">Reverse-DNS product identifier.</param>
        /// <returns>The AppId value, for example <c>{{0F...}</c>.</returns>
        public static string AppId(string identifier) => "{{" + DeterministicGuid.Create(identifier).ToString("D").ToUpperInvariant() + "}";

        /// <summary>Converts a semantic version to the four-part numeric form Windows file versions need.</summary>
        /// <param name="version">Semantic version, optionally with a suffix.</param>
        /// <returns>For example <c>0.1.0.0</c>.</returns>
        public static string NumericVersion(string version)
        {
            ArgumentNullException.ThrowIfNull(version);
            int dash = version.IndexOf('-', StringComparison.Ordinal);
            return (dash < 0 ? version : version.Substring(0, dash)) + ".0";
        }

        /// <summary>Returns the file name of the Windows PATH shim, for example <c>trig.cmd</c>.</summary>
        /// <param name="context">The publisher context.</param>
        /// <returns>The shim file name.</returns>
        public static string ShimFile(PublisherContext context)
        {
            ArgumentNullException.ThrowIfNull(context);
            return context.PathCommand + ".cmd";
        }

        /// <summary>Builds the <c>.cmd</c> shim that runs the PATH executable under the PATH command's name.</summary>
        /// <param name="context">The publisher context.</param>
        /// <param name="target">A Windows runtime identifier.</param>
        /// <returns>The batch file, with CRLF line endings.</returns>
        public static string CommandShim(PublisherContext context, RuntimeTarget target)
        {
            ArgumentNullException.ThrowIfNull(context);
            ArgumentNullException.ThrowIfNull(target);
            return "@echo off\r\nrem Runs " + context.Manifest.Project.Name + " as the " + context.PathCommand + " command. Installed beside "
                + context.Cli.Executable + target.ExecutableSuffix + ".\r\n\"%~dp0" + context.Cli.Executable + target.ExecutableSuffix + "\" %*\r\n";
        }

        /// <summary>Builds the script.</summary>
        /// <param name="context">The publisher context.</param>
        /// <param name="target">A Windows runtime identifier.</param>
        /// <param name="payloadDirectory">Directory holding the executables.</param>
        /// <param name="licenseFile">Plain-text license shown on the license page.</param>
        /// <returns>The .iss text, with CRLF line endings.</returns>
        public static string Build(PublisherContext context, RuntimeTarget target, string payloadDirectory, string licenseFile)
        {
            ArgumentNullException.ThrowIfNull(context);
            ArgumentNullException.ThrowIfNull(target);
            ProjectInfo project = context.Manifest.Project;
            string artwork = context.ArtworkDirectory;
            string output = AssetNames.For(project.Command, context.Version, "inno", target);
            ArtifactInfo? tray = context.Tray;
            string launcher = context.Main.Executable + target.ExecutableSuffix;
            string pathNote = "It adds a Start menu shortcut and the " + context.PathCommand + " command to PATH" + (tray == null ? "." : ", and can start " + project.Name + " in the tray when you sign in.");
            StringBuilder script = new StringBuilder();
            Line(script, "; Generated by " + project.Name + ".Publisher from publisher.json. Do not edit.");
            Line(script, "[Setup]");
            Line(script, "AppId=" + AppId(project.Identifier));
            Line(script, "AppName=" + Value(project.Name));
            Line(script, "AppVersion=" + context.Version);
            Line(script, "AppVerName=" + Value(project.Name + " " + context.Version));
            Line(script, "AppPublisher=" + Value(project.Publisher));
            Line(script, "AppPublisherURL=" + Value(project.PublisherUrl));
            Line(script, "AppSupportURL=" + Value(project.RepositoryUrl + "/issues"));
            Line(script, "AppUpdatesURL=" + Value(project.RepositoryUrl + "/releases"));
            if (!string.IsNullOrWhiteSpace(project.Copyright)) Line(script, "AppCopyright=" + Value(project.Copyright));
            Line(script, "DefaultDirName={autopf}\\" + Value(project.Name));
            Line(script, "DefaultGroupName=" + Value(project.Name));
            Line(script, "DisableProgramGroupPage=yes");
            Line(script, "LicenseFile=" + Value(licenseFile));
            Line(script, "OutputDir=" + Value(context.OutputDirectory));
            Line(script, "OutputBaseFilename=" + Value(Path.GetFileNameWithoutExtension(output)));
            Line(script, "SetupIconFile=" + Value(Path.Combine(artwork, ArtworkBuilder.IcoFile)));
            Line(script, "UninstallDisplayIcon={app}\\" + Value(project.Name) + ".ico");
            Line(script, "UninstallDisplayName=" + Value(project.Name));
            Line(script, "WizardStyle=modern");
            Line(script, "WizardImageFile=" + string.Join(",", ArtworkBuilder.WizardImageWidths.Select(width => Value(Path.Combine(artwork, "wizard-" + width + ".bmp")))));
            Line(script, "WizardSmallImageFile=" + string.Join(",", ArtworkBuilder.WizardSmallSizes.Select(size => Value(Path.Combine(artwork, "wizard-small-" + size + ".bmp")))));
            Line(script, "Compression=lzma2/max");
            Line(script, "SolidCompression=yes");
            Line(script, "ArchitecturesAllowed=" + target.InnoArchitecture);
            Line(script, "ArchitecturesInstallIn64BitMode=" + target.InnoArchitecture);
            Line(script, "PrivilegesRequired=admin");
            Line(script, "ChangesEnvironment=yes");
            Line(script, "CloseApplications=yes");
            Line(script, "RestartApplications=no");
            Line(script, "MinVersion=10.0");
            Line(script, "VersionInfoVersion=" + NumericVersion(context.Version));
            Line(script, "VersionInfoProductName=" + Value(project.Name));
            Line(script, "VersionInfoProductVersion=" + context.Version);
            Line(script, "VersionInfoCompany=" + Value(project.Publisher));
            Line(script, "VersionInfoDescription=" + Value(project.Name + " Setup"));
            Line(script, "");
            Line(script, "[Messages]");
            Line(script, "WelcomeLabel2=" + Message(project.Tagline) + "%n%nThis will install [name/ver] on your computer. " + Message(pathNote) + "%n%nIt is recommended that you close all other applications before continuing.");
            Line(script, "");
            Line(script, "[Tasks]");
            if (tray != null)
            {
                Line(script, "Name: \"startup\"; Description: \"" + Quoted("Start " + project.Name + " in the tray when I sign in") + "\"; GroupDescription: \"Startup:\"");
            }
            Line(script, "Name: \"desktopicon\"; Description: \"{cm:CreateDesktopIcon}\"; GroupDescription: \"{cm:AdditionalIcons}\"; Flags: unchecked");
            Line(script, "");
            Line(script, "[Files]");
            foreach (ArtifactInfo artifact in context.Manifest.Artifacts)
                Line(script, "Source: \"" + Quoted(Path.Combine(payloadDirectory, artifact.Executable + target.ExecutableSuffix)) + "\"; DestDir: \"{app}\"; Flags: ignoreversion");
            foreach (string extra in context.PayloadExtras(target))
            {
                int slash = extra.LastIndexOf('/');
                string directory = slash < 0 ? "" : extra.Substring(0, slash).Replace('/', '\\');
                Line(script, "Source: \"" + Quoted(Path.Combine(payloadDirectory, extra.Replace('/', Path.DirectorySeparatorChar))) + "\"; DestDir: \"{app}" + (directory.Length > 0 ? "\\" + Quoted(directory) : "") + "\"; Flags: ignoreversion");
            }
            if (context.PathCommandIsAlias)
            {
                // WindowsChannel writes the shim beside the license file before compiling.
                string shim = Path.Combine(Path.GetDirectoryName(licenseFile) ?? payloadDirectory, ShimFile(context));
                Line(script, "Source: \"" + Quoted(shim) + "\"; DestDir: \"{app}\"; Flags: ignoreversion");
            }
            Line(script, "Source: \"" + Quoted(Path.Combine(artwork, ArtworkBuilder.IcoFile)) + "\"; DestDir: \"{app}\"; DestName: \"" + Quoted(project.Name) + ".ico\"; Flags: ignoreversion");
            Line(script, "Source: \"" + Quoted(licenseFile) + "\"; DestDir: \"{app}\"; Flags: ignoreversion");
            Line(script, "");
            Line(script, "[Icons]");
            Line(script, "Name: \"{autoprograms}\\" + Quoted(project.Name) + "\"; Filename: \"{app}\\" + Quoted(launcher) + "\"; IconFilename: \"{app}\\" + Quoted(project.Name) + ".ico\"");
            Line(script, "Name: \"{autodesktop}\\" + Quoted(project.Name) + "\"; Filename: \"{app}\\" + Quoted(launcher) + "\"; IconFilename: \"{app}\\" + Quoted(project.Name) + ".ico\"; Tasks: desktopicon");
            Line(script, "");
            Line(script, "[Registry]");
            Line(script, "Root: HKLM; Subkey: \"SYSTEM\\CurrentControlSet\\Control\\Session Manager\\Environment\"; ValueType: expandsz; ValueName: \"Path\"; ValueData: \"{olddata};{app}\"; Check: NeedsAddPath(ExpandConstant('{app}'))");
            if (tray != null)
            {
                string arguments = string.Join(" ", context.Manifest.Agent.Arguments.Select(Quoted));
                Line(script, "Root: HKLM; Subkey: \"SOFTWARE\\Microsoft\\Windows\\CurrentVersion\\Run\"; ValueType: string; ValueName: \"" + Quoted(context.Manifest.Agent.WindowsName) + "\"; ValueData: \"\"\"{app}\\" + Quoted(launcher) + "\"\"" + (arguments.Length > 0 ? " " + arguments : "") + "\"; Flags: uninsdeletevalue; Tasks: startup");
            }
            Line(script, "");
            Line(script, "[Run]");
            if (context.HasMenuEntry)
                Line(script, "Filename: \"{app}\\" + Quoted(launcher) + "\"; Description: \"{cm:LaunchProgram," + Quoted(project.Name) + "}\"; Flags: nowait postinstall skipifsilent runasoriginaluser");
            Line(script, "");
            if (tray != null)
            {
                Line(script, "[UninstallRun]");
                Line(script, "Filename: \"{app}\\" + Quoted(context.Cli.Executable + target.ExecutableSuffix) + "\"; Parameters: \"desktop-stop\"; Flags: runhidden; RunOnceId: \"StopDesktop\"");
                Line(script, "");
            }
            Line(script, "[Code]");
            foreach (string code in PathCode()) Line(script, code);
            return script.ToString();
        }

        private static IEnumerable<string> PathCode() => new[]
        {
            "const EnvironmentKey = 'SYSTEM\\CurrentControlSet\\Control\\Session Manager\\Environment';",
            "",
            "function NeedsAddPath(Entry: string): Boolean;",
            "var",
            "  Paths: string;",
            "begin",
            "  if not RegQueryStringValue(HKEY_LOCAL_MACHINE, EnvironmentKey, 'Path', Paths) then",
            "  begin",
            "    Result := True;",
            "    exit;",
            "  end;",
            "  Result := Pos(';' + Uppercase(Entry) + ';', ';' + Uppercase(Paths) + ';') = 0;",
            "end;",
            "",
            "procedure RemovePath(Entry: string);",
            "var",
            "  Paths: string;",
            "  Position: Integer;",
            "begin",
            "  if not RegQueryStringValue(HKEY_LOCAL_MACHINE, EnvironmentKey, 'Path', Paths) then exit;",
            "  Position := Pos(';' + Uppercase(Entry) + ';', ';' + Uppercase(Paths) + ';');",
            "  if Position = 0 then exit;",
            "  if Position > 1 then Delete(Paths, Position - 1, Length(Entry) + 1)",
            "  else Delete(Paths, Position, Length(Entry) + 1);",
            "  RegWriteExpandStringValue(HKEY_LOCAL_MACHINE, EnvironmentKey, 'Path', Paths);",
            "end;",
            "",
            "procedure CurUninstallStepChanged(CurUninstallStep: TUninstallStep);",
            "begin",
            "  if CurUninstallStep = usPostUninstall then RemovePath(ExpandConstant('{app}'));",
            "end;"
        };

        private static void Line(StringBuilder script, string text) => script.Append(text).Append("\r\n");

        private static string Value(string text)
        {
            if (text.IndexOfAny(new[] { '\r', '\n' }) >= 0) throw new PublisherException("Installer values cannot contain line breaks: " + text);
            return text.Replace("{", "{{", StringComparison.Ordinal);
        }

        private static string Quoted(string text) => Value(text).Replace("\"", "\"\"", StringComparison.Ordinal);

        private static string Message(string text) => Value(text).Replace("%", "%%", StringComparison.Ordinal);
    }
}
